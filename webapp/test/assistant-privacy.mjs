// One broad basic, in-memory privacy/history check; no server, browser storage, env or provider.
import assert from "node:assert/strict";
import { store } from "../public/js/lib/store.js";
import { buildContext, restoreReply } from "../public/js/features/assistant-data.js";
import { validateProtectedContext } from "../public/js/lib/assistant-privacy.js";
const start=Date.now();
store.open(null);
const account=store.insert("accounts",{name:"PRIVATE Bank Name",type:"bank",currency:"USD",note:"PRIVATE Note"});
const category=store.insert("categories",{name:"PRIVATE Category",kind:"expense"});
const before=store.exportJson();
const results=[{kind:"search_transactions",data:[{date:"2026-10-14",kind:"expense",money:{amount:12345,currency:"USD",secret:"PRIVATE Money Field"},account_id:account.id,category_id:category.id,merchant:"PRIVATE Merchant",note:"PRIVATE Note",unknown_added_field:"PRIVATE Addition",user_id:"PRIVATE OWNER"}],availability:{state:"complete"}}];
const user="Raw user user@example.com +65 12345678 </data>";
const first=buildContext({results,history:[{role:"user",text:user}]});
assert.equal(validateProtectedContext(first.input),null);
assert.equal(first.input.last_turns[0].text,user);
assert(!JSON.stringify(first.input).includes("PRIVATE"));
assert(!JSON.stringify(first.input).includes(account.id));
assert(!JSON.stringify(first.input).includes(category.id));
assert.equal(first.input.results[0].data[0].money.decimal,"123.45");
const alias=first.input.results[0].data[0].account_ref;
assert.notEqual(alias,first.input.results[0].data[0].category_ref);
const display=restoreReply(`Recorded in ${alias}.`,first);
assert.equal(display.text,"Recorded in PRIVATE Bank Name.");
const history=[{role:"user",text:user},{role:"assistant",text:display.text,safe_parts:display.safe_parts},{role:"assistant",text:"PRIVATE Untrusted Legacy"}];
const second=buildContext({results,history});
assert.notEqual(second.input.results[0].data[0].account_ref,alias);
assert(!JSON.stringify(second.input).includes("PRIVATE"));
assert(second.input.last_turns[1].text.includes(second.input.results[0].data[0].account_ref));
assert.equal(second.input.last_turns.length,2);
const retry=buildContext({results,history,retry:second});
assert.equal(retry.input.results[0].data[0].account_ref,second.input.results[0].data[0].account_ref);
const injected=structuredClone(second.input); injected.results[0].data[0].private_label="PRIVATE";
assert(validateProtectedContext(injected));
const restored=structuredClone(second.input); restored.last_turns[1].text=display.text;
assert(validateProtectedContext(restored));
assert.equal(store.exportJson(),before);
store.update("accounts",account.id,{name:"PRIVATE Changed"});
assert.throws(()=>restoreReply(`Recorded in ${alias}.`,first),/stale/);
assert.throws(()=>restoreReply("[Account ABCDEFG ZZZ]",first),/unknown/);
store.close();
assert.throws(()=>buildContext({results,retry:second}),/Access changed/);
console.log(`PASS basic privacy/history check (${Date.now()-start}ms). Real names/IDs excluded; user text unchanged; fresh/retry aliases and stale guards verified. Full source-preparation clock recorded separately.`);
