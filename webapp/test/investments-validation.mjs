// Focused investment validation checks; isolated in-memory store, no browser or network.
import assert from 'node:assert/strict';
Object.defineProperty(globalThis,'navigator',{value:{storage:null},configurable:true});
globalThis.location={hash:'#/investments'};globalThis.window={scrollTo(){}};
globalThis.document={getElementById:()=>({innerHTML:''}),querySelector:()=>null,querySelectorAll:()=>[],body:{}};
globalThis.fetch=async()=>{throw new Error('Unexpected network call');};
const P=new URL('../public/js/',import.meta.url).href,M=p=>import(P+p);
const {store}=await M('lib/store.js'),{money}=await M('lib/money.js'),profile=await M('features/profile.js'),I=await M('features/investments.js');
profile.createProfile({base_currency:'SGD',timezone:'UTC',self_description:'working',ai_provider:false});
const today=profile.today(),holding=I.create({name:'Fund',type:'fund',currency:'SGD',mode:'units'});
const reject=(fn,field)=>{const before=store.snapshot();assert.throws(fn,e=>!!e.fields?.[field]);assert.deepEqual(store.snapshot(),before);};
reject(()=>I.create({name:' ',type:'bad',currency:'XYZ',mode:'bad'}),'name');
reject(()=>I.trade(holding.id,'buy',today,'2',money(10,'USD'),null),'price');
reject(()=>I.trade(holding.id,'buy','2026-02-30','2',money(10,'SGD'),null),'date');
reject(()=>I.trade(holding.id,'buy',today,'2',money(Number.MAX_SAFE_INTEGER,'SGD'),money(2,'SGD')),'price');
reject(()=>I.trade(holding.id,'buy',today,'not-units',money(10,'SGD'),null),'units');
const usd=I.create({name:'USD fund',type:'fund',currency:'USD',mode:'value'});
const usdUnits=I.create({name:'USD units',type:'fund',currency:'USD',mode:'units'});
const independentTrade=I.collectTrade(usdUnits.id,'buy',today,'bad',null,null,'bad');
assert.ok(independentTrade.fields.units&&independentTrade.fields.price&&independentTrade.fields.rate,'rate issue is collected alongside unrelated trade amount errors');
const badDateRate=I.collectEntry(usd.id,'manual','2026-02-30',money(100,'USD'),'bad');
assert.ok(badDateRate.fields.date&&!badDateRate.fields.rate,'invalid date does not create a rate error');
const missingRate=(()=>{try{I.value(usd.id,today,money(100,'USD'));}catch(e){return e;}})();
assert.deepEqual(missingRate.rate_pair,{from:'USD',to:'SGD',date:today});
reject(()=>I.value(usd.id,today,money(100,'USD'),'manual',{rate:'999999999999999999999'}),'value');
I.trade(holding.id,'buy',today,'2',money(100,'SGD'),null);
reject(()=>I.trade(holding.id,'sell',today,'2.1',money(100,'SGD'),null),'units');
I.trade(holding.id,'buy',today,'1',money(10,'SGD'),money(-1,'SGD'));
const flow=I.cashFlow(holding.id,'withdrawal',today,money(100,'SGD'));
const valuation=I.value(holding.id,today,money(0,'SGD'));
const signedValuation=I.value(holding.id,today,money(-5,'SGD'));
assert.equal(flow.money.amount,100);assert.equal(valuation.value.amount,0);assert.equal(signedValuation.value.amount,-5);
assert.throws(()=>I.cashFlow(holding.id,'deposit',today,money(0,'SGD')));
console.log('PASS investments validation and permitted zero valuation / positive flow');
